// The PR body (02 §2.2; brief 5): the description, one compact trailer line, the footer, then the hidden
// `pr` block. No sections and no test logs: the user's standing correction is "2–3 sentences".
//
// Rendering reads the block, not the create input, so `pr edit` re-renders from the merged block (02 §3).
// The block goes through the wave 1 codec (src/meta/codec.ts), which owns the wire format: keys sorted,
// `<`, `>` and `&` escaped.
import type { GhxConfig } from '../config/schema.ts';
import { GhxError } from '../core/errors.ts';
import { encode, MAX_BODY_CHARS } from '../meta/codec.ts';
import type { PrCreateInput } from '../pr/create/schema.ts';
import type { TestingItem } from '../schemas/pr.ts';
import { VERSION } from '../version.ts';
import { inlineCode, joinParagraphs, joinTrailer } from './markdown.ts';

/** The fields of a create input that the `pr` block keeps (02 §9.2): not base, head or draft. */
type BlockFields = Omit<PrCreateInput, 'base' | 'head' | 'draft'>;

/** The `pr` block payload as written (02 §9.2). M6.1's strict PrBlock schema validates the same shape. */
export type PrBlockData = { t: 'pr'; id: string; gen: string; rev: number } & BlockFields;

export interface PrBlockMeta {
  /** `p_` plus 6 Crockford chars, generated by the caller (02 §1.4). */
  id: string;
  /** 1 on create; `pr edit` increments it. */
  rev?: number;
  /** `ghx/<semver>`; defaults to this build's version. */
  gen?: string;
}

export type RenderOptions = Pick<GhxConfig['render'], 'mode' | 'footer'>;

/** The block for a create input: its content fields plus t, id, gen and rev. Absent optionals stay absent. */
export function toPrBlock(input: BlockFields, meta: PrBlockMeta): PrBlockData {
  const block: PrBlockData = {
    t: 'pr',
    id: meta.id,
    gen: meta.gen ?? `ghx/${VERSION}`,
    rev: meta.rev ?? 1,
    title: input.title,
    description: input.description,
    testing: input.testing,
    risk: input.risk,
    components: input.components,
    revertPolicy: input.revertPolicy,
  };
  if (input.riskNote !== undefined) block.riskNote = input.riskNote;
  if (input.revertNote !== undefined) block.revertNote = input.revertNote;
  if (input.revertWith !== undefined) block.revertWith = input.revertWith;
  if (input.refs !== undefined) block.refs = input.refs;
  return block;
}

const NON_PASS = ['fail', 'skipped', 'not-run'] as const;

/** `3/3 pass (unit, integration, typecheck)` or `2/3 pass, 1 not-run (unit, e2e, manual)`. */
export function testSummary(testing: readonly TestingItem[]): string {
  const count = (r: string) => testing.filter((t) => t.result === r).length;
  const others = NON_PASS.filter((r) => count(r) > 0).map((r) => `, ${count(r)} ${r}`);
  const kinds = [...new Set(testing.map((t) => t.kind))].join(', ');
  return `${count('pass')}/${testing.length} pass${others.join('')} (${kinds})`;
}

/**
 * The one visible metadata line. Stack and close refs are visible so GitHub links and auto-closes them;
 * GitHub needs the keyword before every issue, hence `Closes #1, closes #2`.
 */
export function renderTrailer(block: PrBlockData): string {
  const refs = block.refs;
  const closes = refs?.closes ?? [];
  return joinTrailer([
    `Risk: ${block.risk}`,
    `Components: ${block.components.join(', ')}`,
    `Revert: ${block.revertPolicy}`,
    `Tests: ${testSummary(block.testing)}`,
    refs?.stackedOn && `Stacked on ${refs.stackedOn}`,
    refs?.splitFrom && `Split from ${refs.splitFrom}`,
    closes.length > 0 ? closes.map((c, i) => `${i === 0 ? 'Closes' : 'closes'} ${c}`).join(', ') : null,
  ]);
}

/** `details` mode: a collapsed list saying how to re-run each test. */
export function renderHowToTest(testing: readonly TestingItem[]): string {
  const items = testing.map((t) => {
    const command = t.command === undefined ? '' : `: ${inlineCode(t.command)}`;
    const cwd = t.cwd === undefined ? '' : ` in ${inlineCode(t.cwd)}`;
    const notes = t.notes === undefined ? '' : ` — ${t.notes}`;
    const steps = (t.steps ?? []).map((s, i) => `\n  ${i + 1}. ${s}`).join('');
    return `- ${t.kind}${command}${cwd} (${t.result})${notes}${steps}`;
  });
  return `<details><summary>How to test</summary>\n\n${items.join('\n')}\n\n</details>`;
}

/** The full body. Throws META_TOO_LARGE over GitHub's 65,536-char limit (02 §2.2). */
export function renderPrBody(block: PrBlockData, opts: RenderOptions): string {
  const body = joinParagraphs([
    block.description,
    renderTrailer(block),
    opts.mode === 'details' ? renderHowToTest(block.testing) : null,
    opts.footer,
    encode(block),
  ]);
  if (body.length > MAX_BODY_CHARS) {
    throw new GhxError('META_TOO_LARGE', `The PR body is ${body.length} characters; GitHub allows ${MAX_BODY_CHARS}.`, {
      hint: 'Shorten the description, notes or steps.',
      details: { chars: body.length, max: MAX_BODY_CHARS },
    });
  }
  return body;
}

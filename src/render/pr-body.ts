// The PR body (02 §2.2, 08 §2): the project's template (render.prBody, or the built-in one render.mode names)
// filled from the block, then the footer, then the hidden `pr` block. The built-in templates have brief
// sections (Summary, How to test, Data); the description itself stays 1–3 plain lines.
//
// Rendering reads the block, not the create input, so `pr edit` re-renders from the merged block (02 §3).
// The block goes through the strict encodeBlock (src/meta/schemas.ts): a block the strict PrBlock rejects is
// a ghx bug (INTERNAL), never a body. The codec owns the wire format: keys sorted, `<`, `>` and `&` escaped.
import type { GhxConfig } from '../config/schema.ts';
import { GhxError } from '../core/errors.ts';
import { MAX_BODY_CHARS, strip } from '../meta/codec.ts';
import { type BlockRead, encodeBlock, readBlocks } from '../meta/schemas.ts';
import type { PrCreateInput } from '../pr/create/schema.ts';
import { VERSION } from '../version.ts';
import { inlineCode, joinParagraphs, joinTrailer } from './markdown.ts';
import { layoutOf, renderTemplate, type TemplateValues, templateText } from './template.ts';

/** The fields of a create input that the `pr` block keeps (02 §9.2): not base, head or draft. */
type BlockFields = Omit<PrCreateInput, 'base' | 'head' | 'draft'>;

/** The `pr` block payload as written (02 §9.2). M6.1's strict PrBlock schema validates the same shape. */
export type PrBlockData = {
  t: 'pr';
  id: string;
  gen: string;
  rev: number;
  alsoTouched?: string[];
  /** The template the body was rendered with (08 §2): 8 hex chars; renderPrBody sets it. */
  layout?: string;
} & BlockFields;

export interface PrBlockMeta {
  /** `p_` plus 6 Crockford chars, generated by the caller (02 §1.4). */
  id: string;
  /** 1 on create; `pr edit` increments it. */
  rev?: number;
  /** `ghx/<semver>`; defaults to this build's version. */
  gen?: string;
  /** Touched by the diff but not in `components` (06). */
  alsoTouched?: readonly string[];
}

export type RenderOptions = Pick<GhxConfig['render'], 'mode' | 'footer'> & {
  /** The project's template (08 §2); the built-in one for `mode` when absent. */
  prBody?: string | readonly string[] | undefined;
  /** The declared data keys, in config order: `{{data}}` lists them first (08 §3). */
  declared?: readonly string[] | undefined;
};

/** The render options a config gives: render.* plus the declared data keys. */
export function renderOptions(config: Pick<GhxConfig, 'render' | 'data'>): RenderOptions {
  return { ...config.render, declared: Object.keys(config.data.fields) };
}

/** The block for a create input: its content fields plus t, id, gen and rev. Absent optionals stay absent. */
export function toPrBlock(input: BlockFields, meta: PrBlockMeta): PrBlockData {
  const block: PrBlockData = {
    t: 'pr',
    id: meta.id,
    gen: meta.gen ?? `ghx/${VERSION}`,
    rev: meta.rev ?? 1,
    title: input.title,
    description: input.description,
    testing: input.testing,
    risk: input.risk,
    components: input.components,
    revertPolicy: input.revertPolicy,
  };
  if (meta.alsoTouched !== undefined && meta.alsoTouched.length > 0) block.alsoTouched = [...meta.alsoTouched];
  if (input.riskNote !== undefined) block.riskNote = input.riskNote;
  if (input.revertNote !== undefined) block.revertNote = input.revertNote;
  // An empty list means "none" (a `pr edit` patch clears it with []); the strict block needs ≥1 or absent.
  if (input.revertWith !== undefined && input.revertWith.length > 0) block.revertWith = input.revertWith;
  if (input.refs !== undefined) block.refs = input.refs;
  if (input.data !== undefined && Object.keys(input.data).length > 0) block.data = input.data;
  return block;
}

const NON_PASS = ['fail', 'skipped', 'not-run'] as const;

/** What the trailer reads. A strict PrBlockData or a lenient PrBlockRead (src/meta/schemas.ts) both fit. */
export interface TrailerSource {
  risk: string;
  components: readonly string[];
  alsoTouched?: readonly string[] | undefined;
  revertPolicy: string;
  testing: readonly { kind: string; result: string }[];
  refs?:
    | { stackedOn?: string | undefined; splitFrom?: string | undefined; closes?: readonly string[] | undefined }
    | undefined;
}

/** `3/3 pass (unit, integration, typecheck)` or `2/3 pass, 1 not-run (unit, e2e, manual)`. */
export function testSummary<T extends { kind: string; result: string }>(testing: readonly T[]): string {
  const count = (r: string) => testing.filter((t) => t.result === r).length;
  const others = NON_PASS.filter((r) => count(r) > 0).map((r) => `, ${count(r)} ${r}`);
  const kinds = [...new Set(testing.map((t) => t.kind))].join(', ');
  return `${count('pass')}/${testing.length} pass${others.join('')} (${kinds})`;
}

/**
 * The one visible metadata line. Stack and close refs are visible so GitHub links and auto-closes them;
 * GitHub needs the keyword before every issue, hence `Closes #1, closes #2`.
 */
export function renderTrailer(block: TrailerSource): string {
  const refs = block.refs;
  const closes = refs?.closes ?? [];
  const more = block.alsoTouched?.length ?? 0;
  return joinTrailer([
    `Risk: ${block.risk}`,
    `Components: ${block.components.join(', ')}${more > 0 ? ` (+${more} more)` : ''}`,
    `Revert: ${block.revertPolicy}`,
    `Tests: ${testSummary(block.testing)}`,
    refs?.stackedOn && `Stacked on ${refs.stackedOn}`,
    refs?.splitFrom && `Split from ${refs.splitFrom}`,
    closes.length > 0 ? closes.map((c, i) => `${i === 0 ? 'Closes' : 'closes'} ${c}`).join(', ') : null,
  ]);
}

/** What the template reads from a block: a strict PrBlockData or a lenient PrBlockRead both fit. */
export interface RenderSource extends TrailerSource {
  title: string;
  description: string;
  testing: readonly TestItemSource[];
  riskNote?: string | undefined;
  revertNote?: string | undefined;
  data?: unknown;
}

interface TestItemSource {
  kind: string;
  result: string;
  command?: string | undefined;
  cwd?: string | undefined;
  steps?: readonly string[] | undefined;
  notes?: string | undefined;
}

/** `{{howToTest}}`: one list item per test, saying how to re-run it. */
export function renderTestList(testing: readonly TestItemSource[]): string {
  return testing
    .map((t) => {
      const command = t.command === undefined ? '' : `: ${inlineCode(t.command)}`;
      const cwd = t.cwd === undefined ? '' : ` in ${inlineCode(t.cwd)}`;
      const notes = t.notes === undefined ? '' : ` — ${t.notes}`;
      const steps = (t.steps ?? []).map((s, i) => `\n  ${i + 1}. ${s}`).join('');
      return `- ${t.kind}${command}${cwd} (${t.result})${notes}${steps}`;
    })
    .join('\n');
}

/** The legacy `details`-mode block (bodies written before 08): the list in a collapsed `<details>`. */
export function renderHowToTest(testing: readonly TestItemSource[]): string {
  return `<details><summary>How to test</summary>\n\n${renderTestList(testing)}\n\n</details>`;
}

/** The block's data as an object; {} when absent or not an object. */
function dataMap(data: unknown): Record<string, unknown> {
  return data !== null && typeof data === 'object' && !Array.isArray(data) ? (data as Record<string, unknown>) : {};
}

/**
 * One data value as markdown (08 §3): always code spans, so a value cannot @mention anyone, auto-close an
 * issue (`Closes #1`) or inject markdown. Lists join their items; objects render `k: v`, sorted by key.
 */
export function dataValueText(v: unknown): string {
  if (Array.isArray(v)) return v.map((x) => inlineCode(String(x))).join(', ');
  if (v !== null && typeof v === 'object') {
    const o = v as Record<string, unknown>;
    return Object.keys(o)
      .sort()
      .map((k) => inlineCode(`${k}: ${String(o[k])}`))
      .join(', ');
  }
  return inlineCode(String(v));
}

/** `{{data}}`: one `- key: value` item per key not placed elsewhere; declared keys first, the rest sorted. */
export function renderDataList(
  data: unknown,
  declared: readonly string[] = [],
  placed: ReadonlySet<string> = new Set(),
): string {
  const map = dataMap(data);
  const keys = Object.keys(map).filter((k) => !placed.has(k));
  const order = [...declared.filter((k) => keys.includes(k)), ...keys.filter((k) => !declared.includes(k)).sort()];
  return order.map((k) => `- ${k}: ${dataValueText(map[k])}`).join('\n');
}

/** The placeholder values for a block. */
function templateValues(block: RenderSource, text: string, declared: readonly string[]): TemplateValues {
  const map = dataMap(block.data);
  const placed = new Set<string>();
  const values: TemplateValues = {};
  for (const m of text.matchAll(/\{\{\s*data\.([a-z][a-zA-Z0-9_-]{0,39})\s*\}\}/g)) {
    const key = m[1] ?? '';
    placed.add(key);
    values[`data.${key}`] = map[key] === undefined ? '' : dataValueText(map[key]);
  }
  const more = block.alsoTouched?.length ?? 0;
  return {
    ...values,
    description: block.description,
    trailer: renderTrailer(block),
    howToTest: renderTestList(block.testing),
    data: renderDataList(map, declared, placed),
    risk: block.risk,
    revertPolicy: block.revertPolicy,
    components: `${block.components.join(', ')}${more > 0 ? ` (+${more} more)` : ''}`,
    testSummary: testSummary(block.testing),
    riskNote: block.riskNote ?? '',
    revertNote: block.revertNote ?? '',
  };
}

/** The visible markdown the template renders for `block` (no footer, no block). */
export function renderVisible(block: RenderSource, opts: RenderOptions): string {
  const text = templateText(opts);
  return renderTemplate(text, templateValues(block, text, opts.declared ?? []));
}

/** The full body, with `layout` recorded in the block. Throws META_TOO_LARGE over GitHub's 65,536 chars. */
export function renderPrBody(block: PrBlockData, opts: RenderOptions): string {
  const full: PrBlockData = { ...block, layout: layoutOf(templateText(opts)) };
  const body = joinParagraphs([renderVisible(full, opts), opts.footer, encodeBlock(full)]);
  if (body.length > MAX_BODY_CHARS) {
    throw new GhxError('META_TOO_LARGE', `The PR body is ${body.length} characters; GitHub allows ${MAX_BODY_CHARS}.`, {
      hint: 'Shorten the description, notes, steps or data.',
      details: { chars: body.length, max: MAX_BODY_CHARS },
    });
  }
  return body;
}

// ── Parse (the inverse of renderPrBody) ───────────────────────────────────
/**
 * A legacy PR body (no `layout` in its block; written before 08) split into the parts that renderer wrote:
 * description, one trailer line, an optional collapsed How to test, the footer and the blocks.
 */
export interface ParsedPrBody {
  /** The visible prose before the trailer; all visible text (minus a known footer) when there is no trailer. */
  description: string;
  /** The trailer line (`Risk: … · Components: …`), or null. */
  trailer: string | null;
  /** The `details`-mode How to test block, or null. */
  howToTest: string | null;
  /** The visible text after the trailer and How to test (the footer, plus anything appended), or null. */
  footer: string | null;
  /** Every ghx block in the body, in order (readBlocks; readPrBlock picks the `pr` one). */
  blocks: BlockRead[];
}

/** The trailer always starts with these two fields; it is found as a paragraph of its own. */
const TRAILER_LINE = /(?:^|\n\n)(Risk: [^\n]* · Components: [^\n]*)(?=\n\n|$)/;
const HOW_TO_TEST = /^<details><summary>How to test<\/summary>[\s\S]*?<\/details>/;

/** The visible text (blocks stripped, CRLF normalised) and the known footer peeled off its end. */
function visibleOf(body: string, footer: string | null | undefined): { visible: string; footer: string | null } {
  let visible = strip(body.replace(/\r\n?/g, '\n')).trim();
  const known = footer?.replace(/\r\n?/g, '\n').trim();
  if (known && (visible === known || visible.endsWith(`\n\n${known}`))) {
    visible = visible.slice(0, visible.length - known.length).trim();
    return { visible, footer: known };
  }
  return { visible, footer: null };
}

/**
 * Split a legacy body into description, trailer, How to test, footer and blocks. CRLF (bodies saved from the
 * GitHub UI) is normalised first. `footer`, when known (config `render.footer`), is peeled off the end even when
 * the trailer is missing.
 */
export function parsePrBody(body: string, opts: { footer?: string | null | undefined } = {}): ParsedPrBody {
  const blocks = readBlocks(body.replace(/\r\n?/g, '\n'));
  const { visible, footer } = visibleOf(body, opts.footer);
  const m = TRAILER_LINE.exec(visible);
  if (!m || m[1] === undefined) return { description: visible, trailer: null, howToTest: null, footer, blocks };
  const start = m.index + (m[0].length - m[1].length);
  let rest = visible.slice(start + m[1].length).trim();
  const how = HOW_TO_TEST.exec(rest);
  if (how) rest = rest.slice(how[0].length).trim();
  const after = [rest, footer].filter((x): x is string => x !== null && x !== '').join('\n\n');
  return {
    description: visible.slice(0, start).trim(),
    trailer: m[1],
    howToTest: how ? how[0] : null,
    footer: after === '' ? null : after,
    blocks,
  };
}

/** `pr status` description.drift: `layout` when the body was rendered by another template (08). */
export type PrBodyDrift = 'title' | 'description' | 'trailer' | 'layout';

/** A body read against its block (08 §2 `layout` and drift). */
export interface BodyReading {
  /** The visible description: the UI-edited text when it drifted and can be located, else the visible text. */
  description: string;
  drift: PrBodyDrift[];
  /** Visible text the template did not render and that is not the description: a UI addition, or null. */
  appended: string | null;
  /** One footer-shaped line at the end that is not the current render.footer (an earlier footer), or null. */
  oldFooter: string | null;
  /** The body was rendered by another template than the current one (or before 08): an edit re-renders it. */
  layoutChanged: boolean;
}

const splitParagraphs = (s: string): string[] =>
  s === ''
    ? []
    : s
        .split(/\n[ \t]*\n/)
        .map((p) => p.trim())
        .filter((p) => p !== '');

/** One line that render.footer could have produced (02 §15: at most 500 chars, no HTML comment). */
export function footerShaped(text: string): boolean {
  return text !== '' && !text.includes('\n') && [...text].length <= 500 && !text.includes('<!--');
}

const SENTINEL = '\u0000ghx-description\u0000';

/**
 * Where the visible PR differs from its block (`pr status` description; `pr edit` DESCRIPTION_DRIFT).
 * - A legacy body (no `layout`) is split by parsePrBody, as before 08; `layoutChanged` is true, and its
 *   drift never says `layout` (only a recorded, different layout does).
 * - A templated body is read by anchors: the description and the trailer must each still be a paragraph.
 *   With the current layout, the paragraphs before and after the description must match the template's, so a
 *   UI edit of the description is located and anything else is `appended` (or an old footer).
 */
export function readBody(
  body: string,
  block: RenderSource & { layout?: unknown },
  opts: RenderOptions,
  title?: string,
): BodyReading {
  const drift: PrBodyDrift[] = [];
  if (title !== undefined && title !== block.title) drift.push('title');
  const description = block.description.replace(/\r\n?/g, '\n').trim();
  const trailer = renderTrailer(block);
  const current = opts.footer?.replace(/\r\n?/g, '\n').trim() || null;

  if (typeof block.layout !== 'string') {
    const p = parsePrBody(body, { footer: opts.footer });
    if (p.description !== description) drift.push('description');
    if (p.trailer !== trailer) drift.push('trailer');
    const tail = p.trailer === null ? null : p.footer;
    const odd = tail !== null && tail !== current;
    return {
      description: p.description,
      drift,
      appended: odd && !footerShaped(tail) ? tail : null,
      oldFooter: odd && footerShaped(tail) ? tail : null,
      layoutChanged: true,
    };
  }

  const { visible } = visibleOf(body, opts.footer);
  const paras = splitParagraphs(visible);
  const layoutChanged = block.layout !== layoutOf(templateText(opts));
  if (!paras.includes(description)) drift.push('description');
  if (!paras.includes(trailer)) drift.push('trailer');
  if (layoutChanged) drift.push('layout');
  const reading = (o: Partial<BodyReading>): BodyReading => ({
    description: paras.includes(description) ? description : visible,
    drift,
    appended: null,
    oldFooter: null,
    layoutChanged,
    ...o,
  });
  if (layoutChanged) return reading({});

  // The template's paragraphs around the description, rendered from the block.
  const around = splitParagraphs(renderVisible({ ...block, description: SENTINEL }, opts));
  const at = around.indexOf(SENTINEL);
  const before = around.slice(0, at);
  const after = around.slice(at + 1);
  const same = (a: readonly string[], b: readonly string[]) => a.length === b.length && a.every((x, i) => x === b[i]);
  if (
    at !== -1 &&
    paras.length >= before.length + after.length + 1 &&
    same(paras.slice(0, before.length), before) &&
    same(paras.slice(paras.length - after.length), after)
  ) {
    return reading({ description: paras.slice(before.length, paras.length - after.length).join('\n\n') });
  }
  // Something besides the description changed: what the template did not render, the description and an
  // edited trailer (reported as trailer drift) aside.
  const expected = new Set(splitParagraphs(renderVisible(block, opts)));
  const extra = paras.filter((p) => !expected.has(p) && p !== current && !/^Risk: [^\n]* · Components: /.test(p));
  const last = extra[extra.length - 1];
  // A line after the current footer is a UI addition; in the footer's place, it is an earlier footer.
  const footerKept = current !== null && paras.includes(current);
  if (
    !footerKept &&
    extra.length === 1 &&
    last !== undefined &&
    last === paras[paras.length - 1] &&
    footerShaped(last)
  ) {
    return reading({ oldFooter: last });
  }
  return reading({ appended: extra.length > 0 ? extra.join('\n\n') : null });
}

/** The drift fields alone (`pr status` description.drift). */
export function prBodyDrift(
  body: string,
  block: RenderSource & { layout?: unknown },
  opts: RenderOptions,
  title?: string,
): PrBodyDrift[] {
  return readBody(body, block, opts, title).drift;
}

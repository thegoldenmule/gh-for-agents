#!/usr/bin/env node
// pnpm codegen: write the source modules derived from files on disk, so ghx never reads its own
// install directory at run time and a bundler (bun build --compile, scripts/build-bin.ts) sees every
// module it needs.
//
//   node scripts/codegen.ts           # write every generated module
//   node scripts/codegen.ts --check   # exit 1 and list the stale modules, write nothing (in pnpm check)
//
// - src/cli/commands.generated.ts: a static lazy import per command file under src/commands.
// - test/helpers/commands.generated.ts: the same for the test-only commands (the --test-hooks binary).
// - src/install/snippet.generated.ts: docs/agents/claude-md-snippet.md as a string, for ghx install.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { scanCommandFiles } from '../src/cli/registry.ts';

export const ROOT = join(import.meta.dirname, '..');
const HEADER = '// Generated by `pnpm codegen`. Do not edit by hand.';

function commandList(root: string, outDir: string, registry: string, what: string): string {
  const rows = scanCommandFiles(join(ROOT, root), '.ts').map(({ file, name }) => {
    const path = relative(join(ROOT, outDir), file).split('\\').join('/');
    const spec = path.startsWith('.') ? path : `./${path}`;
    return `  { name: [${name.map((n) => `'${n}'`).join(', ')}], load: () => import('${spec}') },`;
  });
  return [
    HEADER,
    `// ${what}: one static lazy import per command file,`,
    '// so a bundler sees each one and a run loads only the command it resolves.',
    `import type { CommandEntry } from '${registry}';`,
    '',
    'export const COMMANDS: readonly CommandEntry[] = [',
    ...rows,
    '];',
    '',
  ].join('\n');
}

/** A single-quoted JS string literal (biome's quote style). */
function quote(s: string): string {
  const body = s
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('\n', '\\n')
    .replaceAll('\r', '\\r')
    .replaceAll('\u2028', '\\u2028')
    .replaceAll('\u2029', '\\u2029');
  return `'${body}'`;
}

function snippetModule(): string {
  const text = readFileSync(join(ROOT, 'docs', 'agents', 'claude-md-snippet.md'), 'utf8');
  return [
    HEADER,
    '// docs/agents/claude-md-snippet.md, the CLAUDE.md block ghx install writes, embedded so the',
    '// standalone binary carries it.',
    'export const CLAUDE_MD_SNIPPET: string =',
    `  ${quote(text)};`,
    '',
  ].join('\n');
}

/** Every generated module, by repo-relative path. */
export function generate(): Map<string, string> {
  return new Map([
    [
      'src/cli/commands.generated.ts',
      commandList('src/commands', 'src/cli', './registry.ts', 'The commands under src/commands'),
    ],
    [
      'test/helpers/commands.generated.ts',
      commandList(
        'test/helpers/commands',
        'test/helpers',
        '../../src/cli/registry.ts',
        'The test-only commands (GHX_TEST_HOOKS=1)',
      ),
    ],
    ['src/install/snippet.generated.ts', snippetModule()],
  ]);
}

/** Paths whose content on disk differs from what generate() produces. */
export function stale(): string[] {
  const out: string[] = [];
  for (const [path, content] of generate()) {
    let current: string | undefined;
    try {
      current = readFileSync(join(ROOT, path), 'utf8');
    } catch {
      current = undefined;
    }
    if (current !== content) out.push(path);
  }
  return out;
}

function main(): void {
  if (process.argv.includes('--check')) {
    const s = stale();
    if (s.length > 0) {
      process.stdout.write(`Stale generated modules (run pnpm codegen): ${s.join(', ')}\n`);
      process.exitCode = 1;
    }
    return;
  }
  for (const [path, content] of generate()) writeFileSync(join(ROOT, path), content);
}

if (import.meta.main) main();
